import json,sys
sys.path.insert(0,'.')
from ui import UI
from caps_tr import TR
C=json.load(open('cues.json'));T=json.load(open('timeline.json'))
for l,chs in TR.items():
    assert len(chs)==7,l
    for i in range(7): assert len(chs[i])==len(C[i]),(l,i,len(chs[i]),len(C[i]))
for k,v in UI.items(): assert len(v)==5 and all(x.strip() for x in v),k
out='/home/claude/fe/site/mx/'
ENTRY={'mx_entry_k','mx_title','mx_title2','mx_desc','mx_btn','mx_archive_btn'}
with open(out+'mx-i18n.js','w') as f:
    f.write('/* MARS documentary — interface strings [en, bn, es, fr, ar]. Generated by mx/build.py. */\nObject.assign(window.FE_T, {\n')
    f.write(',\n'.join(' %s:%s'%(k,json.dumps(v,ensure_ascii=False)) for k,v in UI.items() if k not in ENTRY)+'\n});\n')
cues={'off':T['offs'],'durs':T['durs'],'total':T['total'],'en':C}
for l,chs in TR.items(): cues[l]=chs
with open(out+'mx-cues.js','w') as f:
    f.write('/* Caption cues. en: [start, end, text] in seconds from the start of each chapter\'s narration; add off[chapter] for the documentary clock. Other languages: translations, same order. */\nwindow.FE_MX_CUES = '+json.dumps(cues,ensure_ascii=False)+';\n')
def ts(x): h=int(x//3600); m=int(x%3600//60); s=x%60; return '%02d:%02d:%06.3f'%(h,m,s)
for l in ['en']+list(TR):
    L=['WEBVTT','',];n=0;txt=[]
    for i in range(7):
        title=UI['mx_c%d'%(i+1)][['en','bn','es','fr','ar'].index(l)]
        n+=1;L+=[str(n),ts(max(0,T['offs'][i]-2.8))+' --> '+ts(T['offs'][i]-0.2),'['+title+']','']
        txt.append('\n'+title.upper()+'\n')
        for j,c in enumerate(C[i]):
            t=c[2] if l=='en' else TR[l][i][j]
            n+=1;L+=[str(n),ts(T['offs'][i]+c[0])+' --> '+ts(T['offs'][i]+c[1]),t,'']
            txt.append(t)
    open(out+'vtt/mars.%s.vtt'%l,'w').write('\n'.join(L))
# entry keys into i18n.js
s=open('/home/claude/fe/site/i18n.js').read()
if '/* mx entry */' not in s:
    i=s.index('/* md entry */')
    blk='/* mx entry */\n'+',\n'.join(' %s:%s'%(k,json.dumps(UI[k],ensure_ascii=False)) for k in sorted(ENTRY))+',\n/* /mx entry */\n'
    open('/home/claude/fe/site/i18n.js','w').write(s[:i]+blk+s[i:])
print('ok',len(UI))
