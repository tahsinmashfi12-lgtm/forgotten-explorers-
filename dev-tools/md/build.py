import json,sys
sys.path.insert(0,'.')
from ui import UI
from caps_tr import TR
C=json.load(open('cues.json'))
keys=list(C)
for lang,chs in TR.items():
    assert len(chs)==6,lang
    for i,k in enumerate(keys): assert len(chs[i])==len(C[k]),(lang,i,len(chs[i]),len(C[k]))
for k,v in UI.items(): assert len(v)==5 and all(x.strip() for x in v),k
out='/home/claude/fe/site/md/'
with open(out+'md-i18n.js','w') as f:
    f.write('/* THE MOON documentary — interface strings [en, bn, es, fr, ar]. Generated by md/build.py. */\nObject.assign(window.FE_T, {\n')
    ENTRY={'md_kicker','md_title','md_sub','md_desc','md_btn','md_archive_btn'}
    f.write(',\n'.join(' %s:%s'%(k,json.dumps(v,ensure_ascii=False)) for k,v in UI.items() if k not in ENTRY))
    f.write('\n});\n')
cues={'en':[[[c['s'],c['e'],c['t']] for c in C[k]] for k in keys]}
for lang,chs in TR.items(): cues[lang]=chs
with open(out+'md-cues.js','w') as f:
    f.write('/* Caption cues per chapter: en = [start, end, text] from word timings of the supplied narration; other languages are translations (same order). */\nwindow.FE_MD_CUES = '+json.dumps(cues,ensure_ascii=False)+';\n')
def ts(x): h=int(x//3600); m=int(x%3600//60); s=x%60; return '%02d:%02d:%06.3f'%(h,m,s)
import os,glob; os.makedirs(out+'vtt',exist_ok=True)
for f in glob.glob(out+'vtt/moon_0*.vtt'): os.remove(f)
DUR=[48.77,53.97,67.55,66.27,67.63,80.35]
for lang in ['en']+list(TR):
    L=['WEBVTT','','NOTE One file for the whole documentary: chapters are timed as if played back to back (each chapter starts where the previous one ends).','']; off=0; n=0
    for i,k in enumerate(keys):
        n+=1; L+=[str(n),ts(off)+' --> '+ts(off+0.9),'['+UI['md_c%d'%(i+1)][['en','bn','es','fr','ar'].index(lang)]+']','']
        for j,c in enumerate(C[k]):
            txt=c['t'] if lang=='en' else TR[lang][i][j]
            n+=1; L+=[str(n),ts(off+max(c['s'],0.95))+' --> '+ts(off+c['e']),txt,'']
        off+=DUR[i]
    open(out+'vtt/moon.%s.vtt'%lang,'w').write('\n'.join(L))
print('ok',len(UI))
